-- [1] 카드 1 이번 분기 매출: 후보 쿼리 네 개 ===================================
--     커피-음료의 2026년 2분기 매출(억 원)을 구하는 쿼리는 (가)~(라) 중 하나.
--     실행하기 전에 읽고 골라서 수업 사이트 문항 1에 답함.
--     그다음 넷을 하나씩 실행해 결과를 옆에 적음.

-- (가)
SELECT ROUND(SUM(당월_매출_금액) / 1e8, 1)
       AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료';

-- (나)
SELECT ROUND(AVG(당월_매출_금액) / 1e8, 1)
       AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;

-- (다)
SELECT ROUND(SUM(당월_매출_금액) / 1e8, 1)
       AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;

-- (라)
SELECT ROUND(SUM(당월_매출_금액) / 1e8, 1)
       AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 / 10 = 2026;


-- [2] 카드 2 전년 같은 분기 대비: 두 분기의 매출을 한 번에 =====================
--     빈칸 ____ 두 곳을 채운 뒤 실행. 결과는 2행(분기마다 1행).
--       첫째 빈칸: 비교할 분기(전년 같은 분기)의 코드
--       둘째 빈칸: 분기마다 묶을 열의 이름
--     증감률(%) = (이번 분기 - 전년 같은 분기) / 전년 같은 분기 * 100
--     계산한 값(소수 첫째 자리)을 수업 사이트 문항 2에 입력.

SELECT 기준_년분기_코드 AS 분기,
       ROUND(SUM(당월_매출_금액) / 1e8, 1) AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (____, 20262)
GROUP BY ____;


