--  실행: 블록 하나를 SELECT부터 ; 까지 마우스로 끌어 선택 -> 오른쪽 클릭 ->
--        Run Query 바로 아래의 Run Selected Query (SQLite 확장의 메뉴)
--        처음 한 번은 데이터베이스로 data/seoul_sales.db를 고름. 결과 창이 비어 있으면 한 번 더 실행
--
--  업종: 커피-음료   비교하는 두 분기: 2025년 2분기(20252)와 2026년 2분기(20262)
--  표 sales의 한 행 = 한 분기 · 한 상권 · 한 업종.
--  상권_구분_코드_명 = 상권 구분. 발달상권, 골목상권, 관광특구, 전통시장 네 가지.
--  당월_매출_금액 = 그 분기의 매출(원). 1e8(1억)로 나누면 억 원.
--  증감률(%) = (이번 - 작년) * 100.0 / 작년      작년 = 전년 같은 분기
--  기여(%p)  = 구분의 변화 금액 * 100.0 / 업종 전체의 작년 매출
--              네 구분의 기여를 더하면 업종 전체의 증감률이 됨
-- =====================================================================


-- [1] 업종 전체: 작년 매출, 이번 매출, 증감률 ===================================
--     CASE WHEN 기준_년분기_코드 = 20252 THEN 당월_매출_금액 END
--       = 2025년 2분기 행이면 매출, 아니면 빈 값(NULL). SUM은 빈 값을 건너뜀.
--     실행하기 전에 결과가 몇 행, 몇 열일지 적어 봄.

SELECT ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20252
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 작년_억,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20262
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 이번_억,
       ROUND(100.0 *
             (SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END))
             / SUM(CASE WHEN 기준_년분기_코드 = 20252
                   THEN 당월_매출_금액 END), 1)
         AS 증감률
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262);


-- [2] 상권 구분별: 작년 매출, 이번 매출, 증감률 =================================
--     [1]에 구분 열(맨 위 줄), GROUP BY, ORDER BY를 더함. 구분마다 1행.
--     실행하기 전에 결과가 몇 행일지 적어 봄.

SELECT 상권_구분_코드_명 AS 구분,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20252
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 작년_억,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20262
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 이번_억,
       ROUND(100.0 *
             (SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END))
             / SUM(CASE WHEN 기준_년분기_코드 = 20252
                   THEN 당월_매출_금액 END), 1)
         AS 증감률
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262)
GROUP BY 상권_구분_코드_명
ORDER BY 증감률 DESC;


-- [3] 구분별 변화 금액 =========================================================
--     [2]에 변화_억(이번 - 작년, 억 원) 열을 더함.
--     실행하기 전에 늘어난 금액이 가장 큰 구분을 골라 수업 사이트 문항 5에 답함.
--     고쳐 보기: 맨 아래 ORDER BY 증감률 DESC를 ORDER BY 변화_억 DESC로 바꿔 다시 실행.

SELECT 상권_구분_코드_명 AS 구분,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20252
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 작년_억,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20262
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 이번_억,
       ROUND((SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END)) / 1e8, 1)
         AS 변화_억,
       ROUND(100.0 *
             (SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END))
             / SUM(CASE WHEN 기준_년분기_코드 = 20252
                   THEN 당월_매출_금액 END), 1)
         AS 증감률
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262)
GROUP BY 상권_구분_코드_명
ORDER BY 증감률 DESC;


-- [4] 구분별 분해표: 기여(%p) ==================================================
--     [3]에 기여_pp 열을 더함. 기여 = 변화 금액 * 100.0 / 업종 전체의 작년 매출.
--     괄호 안 SELECT가 업종 전체의 작년 매출(숫자 하나)을 구해 네 행 모두의 분모로 씀.
--     직접 쓰지 않고 읽고 실행함. 실행하기 전에 발달상권의 기여를 손으로 계산해 문항 6에 답함.
--     네 행의 기여_pp를 더하면 [1]의 증감률과 같은지 확인.

SELECT 상권_구분_코드_명 AS 구분,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20252
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 작년_억,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20262
                 THEN 당월_매출_금액 END) / 1e8, 1)
         AS 이번_억,
       ROUND((SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END)) / 1e8, 1)
         AS 변화_억,
       ROUND(100.0 *
             (SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END))
             / SUM(CASE WHEN 기준_년분기_코드 = 20252
                   THEN 당월_매출_금액 END), 1)
         AS 증감률,
       ROUND(100.0 *
             (SUM(CASE WHEN 기준_년분기_코드 = 20262
                  THEN 당월_매출_금액 END)
            - SUM(CASE WHEN 기준_년분기_코드 = 20252
                  THEN 당월_매출_금액 END))
             / (SELECT SUM(당월_매출_금액)
                FROM   sales
                WHERE  서비스_업종_코드_명 = '커피-음료'
                  AND  기준_년분기_코드 = 20252), 2)
         AS 기여_pp
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262)
GROUP BY 상권_구분_코드_명
ORDER BY 기여_pp DESC;


-- [5] 내 업종 고르기 ===========================================================
--     업종 목록(62행). 고를 업종 이름을 결과 창에서 그대로 복사함.
--     커피-음료와 치킨전문점은 수업에서 예로 풀었음. 완구는 골목상권의 2025년 2분기 자료가
--     없어 변화가 빈 값으로 나오므로 고르지 않음.
--     Ctrl+H: 찾기 칸에 따옴표를 붙인 커피-음료, 바꾸기 칸에 따옴표를 붙인 내 업종
--     -> 모두 바꾸기(Ctrl+Alt+Enter). [1]~[4]와 [부록]의 업종 이름 7곳이 한 번에 바뀜.
--     그다음 [1]과 [4]를 다시 실행해 분해표를 채우고 수업 사이트 문항 8에 냄.

SELECT DISTINCT 서비스_업종_코드_명 AS 업종
FROM   sales
ORDER BY 업종;


-- [부록] 기여 = 작년 비중 * 구분 증감률 / 100 확인 (읽기용) =======================
--     괄호 안 SELECT가 구분마다 작년, 이번, 업종 전체의 작년 매출을 한 행씩 만들고
--     바깥 SELECT가 그 값으로 비중, 증감률, 둘의 곱, 기여를 계산함.
--     곱 = 작년_비중 * 증감률 / 100. 반올림 전 값으로 계산하면 기여_pp와 같음.
--     증감률은 소수 셋째 자리까지 보여 줌. 그래야 보이는 두 숫자를 곱해도 기여_pp가 나옴
--     (예: 69.27 * 3.528 / 100 = 2.44. 3.53으로 곱하면 2.45가 됨).

SELECT 구분,
       ROUND(100.0 * 작년 / 전체_작년, 2) AS 작년_비중,
       ROUND(100.0 * (이번 - 작년) / 작년, 3) AS 증감률,
       ROUND((100.0 * 작년 / 전체_작년)
             * (100.0 * (이번 - 작년) / 작년) / 100, 2) AS 곱,
       ROUND(100.0 * (이번 - 작년) / 전체_작년, 2) AS 기여_pp
FROM (SELECT 상권_구분_코드_명 AS 구분,
             SUM(CASE WHEN 기준_년분기_코드 = 20252
                 THEN 당월_매출_금액 END) AS 작년,
             SUM(CASE WHEN 기준_년분기_코드 = 20262
                 THEN 당월_매출_금액 END) AS 이번,
             (SELECT SUM(당월_매출_금액)
              FROM   sales
              WHERE  서비스_업종_코드_명 = '커피-음료'
                AND  기준_년분기_코드 = 20252) AS 전체_작년
      FROM   sales
      WHERE  서비스_업종_코드_명 = '커피-음료'
        AND  기준_년분기_코드 IN (20252, 20262)
      GROUP BY 상권_구분_코드_명)
ORDER BY 기여_pp DESC;
