--  표 sales의 한 행 = 한 분기 · 한 상권 · 한 업종.
--  당월_매출_금액 = 그 분기의 매출(원). 1e8(1억)로 나누면 억 원.
--  당월_매출_건수 = 그 분기의 결제 건수(건).
--  매출 = 결제 건수 × 건당 금액
