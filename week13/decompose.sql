-- [1] 매출과 결제 건수: 커피-음료 2026년 2분기 =================================
--     실행하기 전에 결제 건수가 몇 건쯤일지 어림해 적어 봄. 그다음 실행.

SELECT ROUND(SUM(당월_매출_금액) / 1e8, 1) AS 매출_억,
       SUM(당월_매출_건수) AS 건수
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;


-- [2] 건당 금액: 후보 쿼리 네 개 =============================================
--     커피-음료 2026년 2분기의 건당 금액(원)을 바르게 구하는 쿼리는 (가)~(라) 중 하나.
--     실행하기 전에 읽고 골라서 수업 사이트 문항 1에 답함.
--     그다음 넷을 하나씩 실행해 결과를 옆에 주석으로 적음.

-- (가)
SELECT ROUND(AVG(1.0 * 당월_매출_금액
             / 당월_매출_건수), 1)
       AS 건당
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;

-- (나)
SELECT ROUND(1.0 * SUM(당월_매출_금액)
             / SUM(당월_매출_건수), 1)
       AS 건당
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;

-- (다)
SELECT ROUND(SUM(1.0 * 당월_매출_금액
             / 당월_매출_건수), 1)
       AS 건당
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;

-- (라)
SELECT ROUND(1.0 * SUM(당월_매출_금액)
             / COUNT(*), 1)
       AS 건당
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;


-- [3] 상권 구분별 건당 금액을 두 방법으로 ======================================
--     건당_합나누기 = (나)의 계산, 건당_평균 = (가)의 계산. 상권 구분마다 따로 구함.
--     실행하기 전에 두 열의 차이가 가장 큰 구분이 어디일지 예측해 봄.

SELECT 상권_구분_코드_명 AS 구분,
       COUNT(*) AS 상권_수,
       SUM(당월_매출_건수) AS 건수,
       ROUND(1.0 * SUM(당월_매출_금액)
             / SUM(당월_매출_건수), 1) AS 건당_합나누기,
       ROUND(AVG(1.0 * 당월_매출_금액
             / 당월_매출_건수), 1) AS 건당_평균
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262
GROUP BY 상권_구분_코드_명
ORDER BY 건수 DESC;


-- [4] 두 분기의 매출, 결제 건수, 건당 금액 ======================================
--     빈칸 ____ 두 곳을 채운 뒤 실행. 결과는 2행(분기마다 1행).
--       첫째 빈칸: 건당 금액을 구할 때 나누는 것
--       둘째 빈칸: 비교할 분기(전년 같은 분기)의 코드

SELECT 기준_년분기_코드 AS 분기,
       ROUND(SUM(당월_매출_금액) / 1e8, 1) AS 매출_억,
       SUM(당월_매출_건수) AS 건수,
       ROUND(1.0 * SUM(당월_매출_금액) / ____, 1)
         AS 건당
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (____, 20262)
GROUP BY 기준_년분기_코드;


-- [5] 증가율 세 개: SQL을 계산기로 ===========================================
--     [4]의 결과 숫자를 그대로 옮겨 적고 실행. 아래 숫자는 커피-음료의 것.
--     증가율(%) = (이번 - 작년) * 100.0 / 작년
--     100.0으로 쓰는 이유: 100으로 쓰면 정수끼리 계산해 몫만 남음(건수_증가율이 1.0으로 나옴).

SELECT ROUND((7285.8 - 7046.3) * 100.0
             / 7046.3, 1) AS 매출_증가율,
       ROUND((92198136 - 90825366) * 100.0
             / 90825366, 1) AS 건수_증가율,
       ROUND((7902.3 - 7758.1) * 100.0
             / 7758.1, 1) AS 건당_증가율;


-- [6] 곱셈 확인: (1 + 건수 증가율) × (1 + 건당 증가율) = (1 + 매출 증가율) ======
--     [5]의 세 숫자를 넣고 실행. 곱과 매출쪽이 소수 셋째 자리 정도까지 같으면 됨.
--     줄어든 값은 음수 그대로 넣음. 예: (1 + -8.1 / 100)

SELECT ROUND((1 + 1.5 / 100)
           * (1 + 1.9 / 100), 4) AS 곱,
       ROUND(1 + 3.4 / 100, 4) AS 매출쪽;


-- [7] 10개 분기의 매출, 결제 건수, 건당 금액 ===================================
--     [4]에서 IN 줄만 지운 쿼리. 실행하기 전에 몇 행이 나올지 예측해 봄.
--     해마다 1분기와 2분기의 건수, 건당 금액이 어떻게 다른지 봄.

SELECT 기준_년분기_코드 AS 분기,
       ROUND(SUM(당월_매출_금액) / 1e8, 1) AS 매출_억,
       SUM(당월_매출_건수) AS 건수,
       ROUND(1.0 * SUM(당월_매출_금액) / SUM(당월_매출_건수), 1)
         AS 건당
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
GROUP BY 기준_년분기_코드;


-- [8] 내 업종 고르기 =========================================================
--     업종 목록(62행). 고를 업종 이름을 결과 창에서 그대로 복사함.
--     Ctrl+H로 '커피-음료'를 '내 업종'으로 따옴표까지 넣어 모두 바꾼 뒤
--     [4]와 [7]을 다시 실행하고, [5]와 [6]에는 내 업종의 숫자를 넣어 실행.
--     분해표(매출, 건수, 건당 금액의 두 분기 값과 증가율)를 채워 수업 사이트 문항 4에 냄.

SELECT DISTINCT 서비스_업종_코드_명 AS 업종
FROM   sales
ORDER BY 업종;


-- [부록] 증가율 세 개를 쿼리 하나로 (읽기용) ======================================
--     [4]의 결과를 숫자로 옮겨 적지 않고, 반올림하기 전의 합으로 바로 계산함.
--     CASE WHEN 조건 THEN 값 END: 조건이 맞는 행은 값, 아니면 빈 값(NULL). SUM은 빈 값을 건너뜀.
--     1.0 *: 합을 소수로 바꿔 둠. 그래야 뒤의 나눗셈에서 몫만 남지 않음.

SELECT ROUND(100.0 * (s1 - s0) / s0, 1) AS 매출_증가율,
       ROUND(100.0 * (c1 - c0) / c0, 1) AS 건수_증가율,
       ROUND(100.0 * (s1 / c1 - s0 / c0) / (s0 / c0), 1)
         AS 건당_증가율
FROM (SELECT 1.0 * SUM(CASE WHEN 기준_년분기_코드 = 20252
                            THEN 당월_매출_금액 END) AS s0,
             1.0 * SUM(CASE WHEN 기준_년분기_코드 = 20262
                            THEN 당월_매출_금액 END) AS s1,
             1.0 * SUM(CASE WHEN 기준_년분기_코드 = 20252
                            THEN 당월_매출_건수 END) AS c0,
             1.0 * SUM(CASE WHEN 기준_년분기_코드 = 20262
                            THEN 당월_매출_건수 END) AS c1
      FROM   sales
      WHERE  서비스_업종_코드_명 = '커피-음료');
