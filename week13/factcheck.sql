-- [1] 문장 ① 이번 분기 매출과 전년 같은 분기 대비 증감률 ===================
--     CASE WHEN 조건 THEN 값 END : 조건이 맞는 행은 값, 아니면 빈 값(NULL). SUM은 빈 값을 건너뜀.
--     결과 1행: 이번_억, 증감률

SELECT ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20262 THEN 당월_매출_금액 END) / 1e8, 1) AS 이번_억,
       ROUND(100.0 *
         (SUM(CASE WHEN 기준_년분기_코드 = 20262 THEN 당월_매출_금액 END)
        - SUM(CASE WHEN 기준_년분기_코드 = 20252 THEN 당월_매출_금액 END))
        / SUM(CASE WHEN 기준_년분기_코드 = 20252 THEN 당월_매출_금액 END), 1) AS 증감률
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262);


-- [2] 문장 ② 직전 분기 대비와 분기 추이 =====================================
--  (가) 빈칸 ____ 세 곳에 직전 분기의 코드를 넣고 실행. 11.9가 나오는지 확인
--       다 되면 수업 사이트 문항 5(문장 ②의 판정)에 답함

SELECT ROUND(100.0 *
         (SUM(CASE WHEN 기준_년분기_코드 = 20262 THEN 당월_매출_금액 END)
        - SUM(CASE WHEN 기준_년분기_코드 = ____ THEN 당월_매출_금액 END))
        / SUM(CASE WHEN 기준_년분기_코드 = ____ THEN 당월_매출_금액 END), 1) AS 직전분기_대비
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (____, 20262);

--  (나) 10개 분기의 매출. 결과 10행. 해마다 1분기와 2분기를 견주어 봄

SELECT 기준_년분기_코드 AS 분기,
       ROUND(SUM(당월_매출_금액) / 1e8, 1) AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
GROUP BY 기준_년분기_코드
ORDER BY 분기;


-- [3] 문장 ③ 상권 구분마다 전년 같은 분기 대비 ================================
--  (가) 상권 구분과 분기, 두 열로 묶음. 결과 8행(구분 4 x 분기 2)
--       전통시장의 증감률(%)을 계산해 소수 첫째 자리까지 수업 사이트 문항 6에 입력

SELECT 상권_구분_코드_명 AS 구분,
       기준_년분기_코드 AS 분기,
       ROUND(SUM(당월_매출_금액) / 1e8, 1) AS 매출_억
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262)
GROUP BY 상권_구분_코드_명, 기준_년분기_코드
ORDER BY 구분, 분기;

--  (나) 한 구분을 한 행으로: [1]의 쿼리에 구분 열과 GROUP BY 한 줄을 더한 것. 결과 4행
--       문항 6에 답한 뒤 실행해 내 계산과 견줌

SELECT 상권_구분_코드_명 AS 구분,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20252 THEN 당월_매출_금액 END) / 1e8, 1) AS 작년_억,
       ROUND(SUM(CASE WHEN 기준_년분기_코드 = 20262 THEN 당월_매출_금액 END) / 1e8, 1) AS 이번_억,
       ROUND(100.0 *
         (SUM(CASE WHEN 기준_년분기_코드 = 20262 THEN 당월_매출_금액 END)
        - SUM(CASE WHEN 기준_년분기_코드 = 20252 THEN 당월_매출_금액 END))
        / SUM(CASE WHEN 기준_년분기_코드 = 20252 THEN 당월_매출_금액 END), 1) AS 증감률
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 IN (20252, 20262)
GROUP BY 상권_구분_코드_명
ORDER BY 증감률 DESC;


-- [4] 문장 ④ 연령대별 매출과 비중 =============================================
--  (가) 실행하기 전에 매출이 가장 큰 연령대를 예측해 수업 사이트 문항 7에 답함
--       연령대 열 여섯 개를 각각 더함. 결과 1행 6열(억 원)

