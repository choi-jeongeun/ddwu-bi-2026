             / SUM(당월_매출_금액), 1) AS 매출_대비,
       ROUND(100.0 * SUM(연령대_30_매출_금액)
             / SUM(연령대_10_매출_금액 + 연령대_20_매출_금액 + 연령대_30_매출_금액
