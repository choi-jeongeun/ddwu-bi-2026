       ROUND(SUM(연령대_20_매출_금액) / 1e8, 1)      AS 이십대,
       ROUND(SUM(연령대_30_매출_금액) / 1e8, 1)      AS 삼십대,
       ROUND(SUM(연령대_40_매출_금액) / 1e8, 1)      AS 사십대,
       ROUND(SUM(연령대_50_매출_금액) / 1e8, 1)      AS 오십대,
       ROUND(SUM(연령대_60_이상_매출_금액) / 1e8, 1) AS 육십대_이상
FROM   sales
WHERE  서비스_업종_코드_명 = '커피-음료'
  AND  기준_년분기_코드 = 20262;

--  (나) 30대의 비중(%)을 분모 두 가지로. 분자는 같고 분모만 다름. 결과 1행 2열

